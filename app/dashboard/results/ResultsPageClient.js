'use client';

import React, { useState, useEffect } from 'react';
import { motion } from 'framer-motion';
import { CircularProgressbar, buildStyles } from 'react-circular-progressbar';
import 'react-circular-progressbar/dist/styles.css';
import CountUp from 'react-countup';
import SimilaritySlider from '@/components/SimilaritySlider';
import HighlightedText from '@/components/HighlightedText';
import SourceMatchCard from '@/components/SourceMatchCard';
import ResultsFilter from '@/components/ResultsFilter';
import { Button } from '@/components/ui/button';
import { Card, CardContent } from '@/components/ui/card';
import { Download, Share2, ArrowLeft, Clock, FileText, Globe, AlertTriangle } from 'lucide-react';
import Link from 'next/link';
import { fadeInUp, staggerContainer } from '@/lib/animations';

export default function ResultsPageClient({ report }) {
    const [threshold, setThreshold] = useState([50]); // 50% default - show more matches
    const [filters, setFilters] = useState({ types: [], minScore: 0 });
    const [sortBy, setSortBy] = useState('scoreDesc');
    const [filteredMatches, setFilteredMatches] = useState(report.matches || []);

    // Share Handler
    const handleShare = async () => {
        const shareUrl = window.location.href;
        if (navigator.share) {
            await navigator.share({
                title: `PlagDetect Report - ${Math.round(report.originalityScore)}% Original`,
                text: `Check out my plagiarism report: ${Math.round(report.originalityScore)}% originality score`,
                url: shareUrl
            });
        } else {
            await navigator.clipboard.writeText(shareUrl);
            alert('Link copied to clipboard!');
        }
    };

    // Export Handler - Generate PDF-like text report
    const handleExport = () => {
        const reportText = `
PLAGDETECT ORIGINALITY REPORT
=============================
Document: ${report.document?.filename || 'Untitled'}
Date: ${new Date(report.createdAt).toLocaleString()}
Originality Score: ${Math.round(report.originalityScore)}%

SUMMARY
-------
Total Matches: ${report.matches?.length || 0}
Words Analyzed: ${report.document?.content?.split(/\\s+/).length || 0}

DETECTED SOURCES
----------------
${(report.matches || []).map((m, i) => `
${i + 1}. ${m.sourceTitle || 'Unknown Source'}
   URL: ${m.sourceUrl}
   Similarity: ${Math.round(m.similarityScore)}%
   Type: ${m.matchType}
`).join('')}

DOCUMENT CONTENT
----------------
${report.document?.content || 'N/A'}

---
Generated by PlagDetect
        `.trim();

        const blob = new Blob([reportText], { type: 'text/plain' });
        const url = URL.createObjectURL(blob);
        const a = document.createElement('a');
        a.href = url;
        a.download = `plagdetect-report-${report.id}.txt`;
        a.click();
        URL.revokeObjectURL(url);
    };


    // Filter Logic
    useEffect(() => {
        let result = report.matches || [];

        // 1. Slider Threshold (Client-side visualization mainly, but also filtering)
        // Here we can choose to Filter strictly or just Highlight. Let's Filter strictly for the list.
        // Actually, UX-wise, the slider usually controls what is considered "Plagiarism".
        result = result.filter(m => m.similarityScore >= threshold[0]);

        // 2. Dropdown Filters
        if (filters.types.length > 0) {
            result = result.filter(m => filters.types.includes(m.matchType));
        }
        if (filters.minScore > 0) {
            result = result.filter(m => m.similarityScore >= filters.minScore);
        }

        // 3. Sorting
        result.sort((a, b) => {
            if (sortBy === 'scoreDesc') return b.similarityScore - a.similarityScore;
            if (sortBy === 'scoreAsc') return a.similarityScore - b.similarityScore;
            return 0;
        });

        setFilteredMatches(result);
    }, [report.matches, threshold, filters, sortBy]);


    const getScoreColor = (score) => {
        if (score >= 80) return '#10B981'; // Green (Safe/Original) - Wait, report.originalityScore is "Originality".
        // Wait, standard convention: 100% Original is Green. 0% is Red.
        // IF report.originalityScore is high -> Green.
        if (score >= 80) return '#10B981';
        if (score >= 50) return '#EAB308';
        return '#EF4444';
    };

    // For Match Scores inside cards: 100% Match is BAD (Red).
    // Confusion check: 
    // report.originalityScore = 100 (Good, Green)
    // match.similarityScore = 100 (Bad, Red)

    return (
        <div className="min-h-screen bg-background pb-20">
            {/* Header / Nav */}
            <div className="border-b border-border/40 bg-background/80 backdrop-blur-md sticky top-0 z-40">
                <div className="container mx-auto px-4 h-16 flex items-center justify-between">
                    <div className="flex items-center gap-4">
                        <Link href="/dashboard">
                            <Button variant="ghost" size="icon">
                                <ArrowLeft className="w-5 h-5" />
                            </Button>
                        </Link>
                        <div>
                            <h1 className="font-semibold text-lg">{report.document?.filename || "Document Analysis"}</h1>
                            <p className="text-xs text-muted-foreground">{new Date(report.createdAt).toLocaleDateString()}</p>
                        </div>
                    </div>
                    <div className="flex items-center gap-2">
                        <Button variant="outline" size="sm" className="gap-2" onClick={handleShare}>
                            <Share2 className="w-4 h-4" /> Share
                        </Button>
                        <Button size="sm" className="gap-2" onClick={handleExport}>
                            <Download className="w-4 h-4" /> Export
                        </Button>
                    </div>
                </div>
            </div>

            <main className="container mx-auto px-4 py-8 space-y-8 max-w-7xl">

                {/* 1. Score Overview Section */}
                <section className="grid grid-cols-1 lg:grid-cols-4 gap-6">
                    {/* Main Score Circle */}
                    <motion.div
                        initial="initial" animate="animate" variants={fadeInUp}
                        className="lg:col-span-1 bg-card/50 border border-border/50 rounded-2xl p-6 flex flex-col items-center justify-center text-center shadow-lg relative overflow-hidden"
                    >
                        <div className="w-48 h-48 relative">
                            <div className="absolute inset-0 bg-primary/10 rounded-full blur-3xl animate-pulse" />
                            <CircularProgressbar
                                value={report.originalityScore}
                                text={`${Math.round(report.originalityScore)}%`}
                                styles={buildStyles({
                                    pathColor: getScoreColor(report.originalityScore),
                                    textColor: getScoreColor(report.originalityScore),
                                    trailColor: '#33333330', // dark mode compatible
                                    textSize: '18px',
                                    pathTransitionDuration: 2, // Animation duration
                                })}
                            />
                        </div>
                        <div className="mt-4 space-y-1">
                            <h2 className="text-2xl font-bold tracking-tight">Originality Score</h2>
                            <p className={`text-sm font-medium px-3 py-1 rounded-full inline-block ${report.originalityScore > 80 ? 'bg-green-500/10 text-green-500' :
                                report.originalityScore > 50 ? 'bg-yellow-500/10 text-yellow-500' : 'bg-red-500/10 text-red-500'
                                }`}>
                                {report.originalityScore > 80 ? "Excellent Work" : report.originalityScore > 50 ? "Moderate Risk" : "High Risk Found"}
                            </p>
                        </div>
                    </motion.div>

                    {/* Stats Cards */}
                    <div className="lg:col-span-3 grid grid-cols-2 lg:grid-cols-4 gap-4">
                        <StatsCard icon={AlertTriangle} label="Total Matches" value={report.matches?.length || 0} delay={0.1} />
                        <StatsCard icon={Globe} label="Sources Found" value={new Set(report.matches?.map(m => m.sourceUrl)).size || 0} delay={0.2} />
                        <StatsCard icon={Clock} label="Processing Time" value="1.2s" delay={0.3} />
                        {/* We didn't store processing time in DB model properly, assume mock or pass via props later */}
                        <StatsCard icon={FileText} label="Words Checked" value={report.document?.content?.split(/\s+/).length || 0} delay={0.4} />
                    </div>
                </section>

                <div className="grid grid-cols-1 xl:grid-cols-3 gap-8">

                    {/* 2. Left Column: Text Viewer */}
                    <motion.div
                        initial={{ opacity: 0, x: -20 }} animate={{ opacity: 1, x: 0 }} transition={{ delay: 0.2 }}
                        className="xl:col-span-2 space-y-6"
                    >
                        <div className="flex items-center justify-between">
                            <h3 className="text-xl font-bold flex items-center gap-2">
                                <FileText className="w-5 h-5 text-primary" />
                                Document Viewer
                            </h3>
                            <div className="w-64">
                                <SimilaritySlider value={threshold} onValueChange={setThreshold} />
                            </div>
                        </div>

                        <Card className="min-h-[600px] border-border/50 bg-card/40 backdrop-blur-sm shadow-xl">
                            <CardContent className="p-8">
                                <HighlightedText
                                    text={report.document?.content || ''}
                                    matches={report.matches || []}
                                    threshold={threshold[0]}
                                />
                            </CardContent>
                        </Card>
                    </motion.div>

                    {/* 3. Right Column: Matches List */}
                    <motion.div
                        initial={{ opacity: 0, x: 20 }} animate={{ opacity: 1, x: 0 }} transition={{ delay: 0.3 }}
                        className="xl:col-span-1 space-y-6"
                    >
                        <h3 className="text-xl font-bold flex items-center gap-2">
                            <Globe className="w-5 h-5 text-primary" />
                            Detected Sources
                        </h3>

                        <ResultsFilter
                            filters={filters}
                            setFilters={setFilters}
                            onSort={setSortBy}
                            matches={filteredMatches}
                        />

                        <div className="space-y-4 max-h-[800px] overflow-y-auto pr-2 custom-scrollbar pb-20">
                            {filteredMatches.length > 0 ? (
                                filteredMatches.map((match, index) => (
                                    <SourceMatchCard key={match.id || index} match={match} delay={index} />
                                ))
                            ) : (
                                <div className="text-center py-12 text-muted-foreground bg-muted/20 rounded-lg border border-dashed">
                                    <p>No matches found with current filters.</p>
                                </div>
                            )}
                        </div>
                    </motion.div>
                </div>

            </main>
        </div>
    );
}

function StatsCard({ icon: Icon, label, value, delay }) {
    return (
        <motion.div
            initial={{ opacity: 0, y: 20 }}
            animate={{ opacity: 1, y: 0 }}
            transition={{ delay }}
            className="bg-card/50 border border-border/50 rounded-xl p-5 shadow-sm hover:shadow-md transition-all hover:-translate-y-1"
        >
            <div className="w-10 h-10 rounded-lg bg-primary/10 flex items-center justify-center text-primary mb-3">
                <Icon className="w-5 h-5" />
            </div>
            <div className="text-2xl font-bold">
                {typeof value === 'number' ? <CountUp end={value} duration={2} /> : value}
            </div>
            <div className="text-xs text-muted-foreground font-medium uppercase tracking-wide mt-1">{label}</div>
        </motion.div>
    )
}
